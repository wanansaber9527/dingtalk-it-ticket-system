export function categoryDefaults(name: string): CategoryDefaults {
  // 先匹配明确的问题对象，避免“系统账号”“网络打印”“电脑软件安装”落入宽泛分支。
  let defaults: CategoryDefaults;
  if (/账号|账户|帐号|密码|权限|登录|登陆|邮箱|account|password|permission|login|authentication/i.test(name)) defaults = ACCOUNT;
  else if (/打印|扫描|复印|printer|printing|scanner/i.test(name)) defaults = PRINTER;
  else if (/数据|报表|统计|导入|导出|excel|csv|report|dashboard/i.test(name)) defaults = DATA;
  else if (/(?:软件|应用|客户端|程序).*(?:安装|升级|更新|卸载)|(?:安装|升级|更新|卸载).*(?:软件|应用|客户端|程序)|software\s+(?:install|upgrade|update)/i.test(name)) defaults = INSTALL;
  else if (/网络|联网|wifi|wi-fi|无线|宽带|vpn|上网|network/i.test(name)) defaults = NETWORK;
  else if (/安装|升级|更新|卸载|install|upgrade/i.test(name)) defaults = INSTALL;
  else if (/业务|管理系统|erp|oa|办公|office|钉钉|business/i.test(name)) defaults = BUSINESS;
  else if (/电脑|硬件|设备|显示|鼠标|键盘|开机|主机|computer|hardware/i.test(name)) defaults = COMPUTER;
  else if (/软件|系统|应用|客户端|浏览器|software|application|browser/i.test(name)) defaults = BUSINESS;
  else defaults = GENERAL;
  // 默认模板不可被调用方的示例编辑污染其他分类。
  return { prompt: defaults.prompt, examples: [...defaults.examples] };
}

